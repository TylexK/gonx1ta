function normalizeCommand(command) {
    const normalized = String(command || '').toLowerCase();
    const canonical = /^[/.#]/.test(normalized) ? `.${normalized.slice(1)}` : normalized;
    return COMMAND_ALIASES.get(canonical) || canonical;
}

function isCommandMessage(message) {
    return /^[/.#]/.test(String(message || ''));
}

function normalizeDisabledCommand(command) {
    const normalized = String(command || '').trim().toLowerCase();
    return normalizeCommand(/^[/.#]/.test(normalized) ? normalized : `.${normalized}`).slice(1);
}

module.exports = {
    COMMAND_ALIASES,
    normalizeCommand,
    isCommandMessage,
    normalizeDisabledCommand
};
